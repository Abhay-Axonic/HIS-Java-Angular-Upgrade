#!/usr/bin/env python3
"""
Renders docs/ANGULAR_PHASE0_SCREEN_INVENTORY.md from data/states_enriched.json.

Generated programmatically rather than hand-written so that a 1,000+ row
table stays internally consistent (counts in the prose always match the
table, every row has the same column count) -- re-run any time the
underlying data changes rather than hand-editing the doc.
"""
import os
import sys
from collections import Counter, defaultdict

from common import STATES_ENRICHED_JSON, INVENTORY_DOC
import json


def tier(s):
    c, b = s["clinical_risk"], s["billing_risk"]
    if c == "yes" and b == "yes":
        return "both"
    if c == "unclear" or b == "unclear":
        return "unclear"
    if c == "yes":
        return "clinical-only"
    if b == "yes":
        return "billing-only"
    return "low-risk"


def main():
    states = json.loads(STATES_ENRICHED_JSON.read_text())
    for s in states:
        s["tier"] = tier(s)

    mod_counts = Counter(s["module"] for s in states)
    tier_counts = Counter(s["tier"] for s in states)
    total = len(states)

    mod_tier = defaultdict(Counter)
    for s in states:
        mod_tier[s["module"]][s["tier"]] += 1

    unresolved_ctrl = [s for s in states if s["ctrl_status"] == "unresolved"]
    no_template = [s for s in states if not s["templateUrl"]]
    view_missing = [s for s in states if s["view_exists"] is False]

    lines = []
    w = lines.append

    w("# Angular Phase 0 - Screen/Route Inventory & Risk Classification")
    w("")
    w("*Generated by `tools/angular-audit/run_audit.py`, a static-analysis pass over the live AngularJS 1.5 routing configuration. Read-only — no application code was touched to produce this document. This is Phase 0 of the frontend rebuild plan: a full inventory and a first-pass risk tag on every screen, so later phases can be sequenced by risk instead of by convenience.*")
    w("")
    w("**How this document was built, in plain terms:** the AngularJS app defines every screen as a \"state\" (a URL + a view template + a controller) in one central routing file. Instead of reading all of those definitions by hand — which would be slow and inconsistent — this was done with a small, reusable tool suite (`tools/angular-audit/`) that parses the actual routing file and cross-references it against the real view and controller files on disk. Risk tags (clinical-safety / billing) were then applied by scanning each screen's name, URL, and file path for a curated list of keywords (e.g. \"transfusion\", \"dose\", \"invoice\", \"tariff\"), plus a per-module default for departments that are clinical or billing by nature (e.g. everything under Blood Bank defaults to clinical-safety-relevant even if the individual screen name doesn't contain an obvious keyword).")
    w("")
    w(f"**This is a first-pass heuristic sort, not a clinical or billing sign-off.** It exists to separate the ~{tier_counts['low-risk']} screens that are most likely safe to rebuild quickly from the ~{tier_counts['both']+tier_counts['clinical-only']+tier_counts['billing-only']} that touch money, patient safety, or both, so the right expert reviews the right screens later (Phase 6). Treat every \"yes\" and \"unclear\" tag below as a starting point for that expert review, not a final verdict — and treat every \"no\" as provisional too: keyword/module matching can miss things a human reader would catch. Where the tooling genuinely couldn't tell (missing files, unresolvable controllers, states with no view), that is called out explicitly below rather than guessed at.")
    w("")
    w("---")
    w("")
    w("## Headline numbers")
    w("")
    w(f"- **Total screens/routes found: {total}** (parsed from `resources/assets/js/config/app.js`, the app's single `$stateProvider` configuration — one line per `.state(...)` call, live code only, commented-out state definitions excluded).")
    w(f"- **{len(mod_counts)} modules/departments** identified from the view-template folder structure.")
    w("- **Risk tiers:**")
    w(f"  - Both clinical-safety AND billing relevant: **{tier_counts['both']}** ({tier_counts['both']*100//total}%)")
    w(f"  - Clinical-safety relevant only: **{tier_counts['clinical-only']}** ({tier_counts['clinical-only']*100//total}%)")
    w(f"  - Billing relevant only: **{tier_counts['billing-only']}** ({tier_counts['billing-only']*100//total}%)")
    w(f"  - Low risk (neither, by this pass): **{tier_counts['low-risk']}** ({tier_counts['low-risk']*100//total}%)")
    w(f"  - Unclear / needs runtime verification: **{tier_counts['unclear']}** ({tier_counts['unclear']*100//total}%)")
    w("")
    w(f"**In plain terms: {tier_counts['both']+tier_counts['clinical-only']+tier_counts['billing-only']} out of {total} screens (roughly {(tier_counts['both']+tier_counts['clinical-only']+tier_counts['billing-only'])*100//total}%) touch either patient safety or money in some way.** Only {tier_counts['low-risk']} screens (about {tier_counts['low-risk']*100//total}%) look administrative/low-risk on this first pass.")
    w("")
    w("## Screens by module")
    w("")
    w("| Module | Screens | Both | Clinical-only | Billing-only | Low-risk | Unclear |")
    w("|---|---:|---:|---:|---:|---:|---:|")
    for mod, cnt in mod_counts.most_common():
        tc = mod_tier[mod]
        w(f"| {mod} | {cnt} | {tc['both']} | {tc['clinical-only']} | {tc['billing-only']} | {tc['low-risk']} | {tc['unclear']} |")
    w("")
    w("---")
    w("")
    w("## Known gaps and things that need runtime verification, not guessing")
    w("")
    w(f"- **{len(unresolved_ctrl)} states reference a controller name that could not be matched to any controller file on disk** by static registration-pattern search (e.g. component-style controllers, unconventional naming, or possibly dead/unused states). Listed individually in the appendix below. These need someone to load the actual screen and confirm what controller (if any) really runs.")
    w(f"- **{len(no_template)} states have no resolvable `templateUrl`** (they use a multi-view `views: {{...}}` block instead of a single template, which this pass did not expand). Listed below.")
    w(f"- **{len(view_missing)} states point at a `templateUrl` that does not exist on disk** at the expected path — likely dead routes, renamed files, or a build-time template pipeline this pass didn't account for. Listed below.")
    shared_count = sum(1 for s in states if s["ctrl_shared"])
    w(f"- **{shared_count} states share one of a small number of generic, reused controllers** (the largest being a single shared `common-controller.js` used by 353 different screens as `MasterController`, a generic CRUD controller that likely branches internally on the current state/URL). For these, the \"API calls\" and \"cross-screen coupling\" columns in the table below reflect the *entire shared controller file*, not the specific screen. Determining the real per-screen behavior for these requires either reading the branching logic inside that shared controller or a runtime trace — see `tools/golden-trace/`, built specifically for this.")
    w("- **Form field counts** are a raw count of `<input>`, `<select>`, and `<textarea>` tags in the view's HTML file. This over-counts on views that conditionally show/hide fields with `ng-if`/`ng-show` and under-counts any field injected dynamically by the controller rather than written directly in the template. Treat it as a rough complexity signal, not an exact form-field census.")
    w("- **Risk tags are keyword/module-heuristic, not a reading of each screen's actual clinical or billing logic.** This is exactly the kind of judgment call Phase 6 assigns to a real clinician/billing reviewer, not to this automated pass.")
    w(f"- **Bed management and appointment-scheduling screens were tagged administrative (low-risk) by default in this pass**, but bed placement can carry real infection-control/isolation implications in some hospitals. Worth a specific yes/no from a clinical lead before treating those {mod_tier['ADT - Bed Management']['low-risk']} bed-management screens as safe to rebuild casually.")
    w("- **`accessControlController` (the controller behind the `accessControl`/`accessControl1` states) is registered twice, in two different files — resolved 2026-07-17, `access-control.js` wins.** `index.html` loads `resources/assets/accessControl/controller/accessControlController.js` at line 1778 (60 lines, a minimal stub — just a `remove` scope function) and then `resources/assets/js/controller/access-control/access-control.js` at line 1786 (373 lines, the full implementation — `$state`/`$cookies`/`GenericService`/`BillingGenericService`/`ivhTreeview*` injected, sets `$scope.title = \"Access Control\"`). AngularJS's `.controller()` registration silently overwrites same-named entries with no error, so whichever loads *last* wins — **`access-control.js` (373 lines) is the one that actually runs; the 60-line stub is dead code, silently shadowed on every page load.** If Phase 2+ ever characterizes an access-control screen, `access-control.js` is the behavior to capture/rebuild — the other file can be deleted separately as a follow-up cleanup, but that's an application-code change outside this doc's read-only scope. Both are still excluded from the API-call/coupling columns above (this bullet documents the fact directly instead).")
    w("- **Four files under the Nursing/pharmacy controller path are unresolved git-merge-tool conflict artifacts** (`addNewbillableConsumptionController_REMOTE_6240.js`, `_BASE_6240.js`, `_BACKUP_6240.js`, `_LOCAL_6240.js`, sitting alongside the real `addNewbillableConsumptionController.js`) — leftover debris from a past merge conflict, excluded from this scan. Worth a separate, low-priority cleanup pass.")
    w("")
    w("---")
    w("")
    w("## Methodology detail")
    w("")
    w("**Route extraction:** every `.state('name', { ... })` call in `app.js` is parsed with a balanced-paren scanner (not a regex-only pass, to correctly handle nested objects like `resolve` blocks). Commented-out state definitions are stripped first and excluded. See `tools/angular-audit/extract_states.py`.")
    w("")
    w("**Module classification:** derived entirely from the view template's folder path, cross-checked against the actual `views/` directory tree on disk. See `classify_risk.py::classify_module`.")
    w("")
    w("**Controller resolution:** every `.js` file under the whole `webapp/` tree (vendor libraries and known dead git-merge-artifact files excluded) is scanned for its actual `.controller('Name', [...])` registration, handling multi-line registrations and controller names containing a literal `.`. See `build_controller_index.py`.")
    w("")
    w("**API-call complexity:** counted as calls to the app's shared HTTP service wrappers (`GenericService.*`, `BillingGenericService.*`, `GenericServiceParamHeader.*`) or raw `$http.get/post/put/delete` inside the resolved controller file. States sharing a heavily-reused generic controller (≥4 states) are marked \"shared\" and show the aggregate count for that shared file instead — not meaningfully per-screen.")
    w("")
    w("**Cross-screen coupling:** each resolved controller file is scanned for `$rootScope.$broadcast(...)`, `$scope.$on(...)`/`$rootScope.$on(...)`, and direct `$rootScope.xxx = ...` writes.")
    w("")
    w("---")
    w("")
    w("## Appendix: states needing runtime verification")
    w("")
    w("### Controller name not resolved to any file")
    w("")
    w("| State | Controller name referenced | Module |")
    w("|---|---|---|")
    for s in unresolved_ctrl:
        w(f"| {s['name']} | {s['controller']} | {s['module']} |")
    w("")
    w("### No single templateUrl (multi-view state, not expanded by this pass)")
    w("")
    w("| State | URL | Module |")
    w("|---|---|---|")
    for s in no_template:
        w(f"| {s['name']} | {s['url'] or ''} | {s['module']} |")
    w("")
    w("### templateUrl does not exist on disk")
    w("")
    w("| State | templateUrl | Module |")
    w("|---|---|---|")
    for s in view_missing:
        w(f"| {s['name']} | {s['templateUrl']} | {s['module']} |")
    w("")
    w("---")
    w("")
    w("## Full screen inventory")
    w("")
    w("Grouped by module. Within each module, sorted risk-first (both → clinical-only → billing-only → unclear → low-risk).")
    w("")
    w("Column notes: **View** = template file relative to `webapp/` (✗ = not found on disk). **Ctrl** = resolved controller file basename, `shared×N` = one of the reused generic controllers, `?` = unresolved, `–` = no controller/multi-view. **Fields** = raw `<input>+<select>+<textarea>` count. **API** = attributable HTTP/service-call count (aggregate when Ctrl is `shared×N`). **Clinical / Billing** = yes/no/unclear with reason. **Coupling** = broadcast(bc)/listen(on)/rootScope-write(rs) counts, aggregate when shared.")
    w("")

    tier_order = {"both": 0, "clinical-only": 1, "billing-only": 2, "unclear": 3, "low-risk": 4}
    by_module = defaultdict(list)
    for s in states:
        by_module[s["module"]].append(s)

    def esc(x):
        return str(x).replace("|", "\\|").replace("\n", " ")

    for mod, cnt in mod_counts.most_common():
        screens = by_module[mod]
        screens.sort(key=lambda s: (tier_order[s["tier"]], s["name"]))
        w(f"### {mod} ({cnt} screens)")
        w("")
        w("| State | URL | View | Ctrl | Fields | API | Clinical | Billing | Coupling |")
        w("|---|---|---|---|---:|---:|---|---|---|")
        for s in screens:
            view = s["templateUrl"] or "–"
            if s["view_exists"] is False:
                view += " ✗"
            elif s["view_exists"] is None:
                view = "–"

            if s["ctrl_status"] == "no-controller":
                ctrl = "–"
            elif s["ctrl_status"] == "unresolved":
                ctrl = "?"
            elif s["ctrl_shared"]:
                ctrl = f"shared×{s['ctrl_usage']}"
            else:
                ctrl = os.path.basename(s["ctrl_files"][0]) if s["ctrl_files"] else "?"

            fields = s["form_fields"] if s["form_fields"] is not None else "–"
            api = s["api_calls"] if s["api_calls"] is not None else "–"

            clin_cell = "no" if s["clinical_risk"] == "no" else f"{s['clinical_risk']} ({s['clinical_reason']})"
            bill_cell = "no" if s["billing_risk"] == "no" else f"{s['billing_risk']} ({s['billing_reason']})"

            if s["ctrl_status"] == "resolved":
                bc, on, rs = len(s["broadcasts"]), len(s["listens"]), s["rootscope_writes"] or 0
                if bc or on:
                    names = []
                    if bc:
                        names.append("bc:" + ",".join(s["broadcasts"][:3]) + ("…" if bc > 3 else ""))
                    if on:
                        names.append("on:" + ",".join(s["listens"][:3]) + ("…" if on > 3 else ""))
                    coupling = f"bc:{bc}/on:{on}/rs:{rs} [{'; '.join(names)}]"
                else:
                    coupling = f"bc:{bc}/on:{on}/rs:{rs}"
            else:
                coupling = "–"

            w(f"| {esc(s['name'])} | {esc(s['url'] or '')} | {esc(view)} | {esc(ctrl)} | {fields} | {api} | {esc(clin_cell)} | {esc(bill_cell)} | {esc(coupling)} |")
        w("")

    INVENTORY_DOC.write_text("\n".join(lines))
    print(f"Wrote {len(lines)} lines -> {INVENTORY_DOC}", file=sys.stderr)


if __name__ == "__main__":
    main()
